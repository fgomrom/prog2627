package ud4.ejercicios;

public class Ejercicio17 {
    public static void main(String[] args) {
        int[] numeros = {1,2,4,5};
        mostrar(numeros);
    }
    
    public static void mostrar(int[] numeros) {
        for(int numero : numeros) {
            System.out.println(numero);
        }
    }
}
